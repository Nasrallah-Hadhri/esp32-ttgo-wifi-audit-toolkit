static void send_cmd(uint8_t cmd) {
    i2c_cmd_handle_t handle = i2c_cmd_link_create();
    i2c_master_start(handle);
    i2c_master_write_byte(handle, (OLED_I2C_ADDR << 1) | I2C_MASTER_WRITE, true);
    i2c_master_write_byte(handle, 0x00, true); // Command stream
    i2c_master_write_byte(handle, cmd, true);
    i2c_master_stop(handle);
    i2c_master_cmd_begin(I2C_MASTER_NUM, handle, 1000 / portTICK_PERIOD_MS);
    i2c_cmd_link_delete(handle);
}

void ssd1306_init() {
    // Reset the OLED display
    gpio_reset_pin(OLED_RST_IO);
    gpio_set_direction(OLED_RST_IO, GPIO_MODE_OUTPUT);
    gpio_set_level(OLED_RST_IO, 0);
    vTaskDelay(50 / portTICK_PERIOD_MS);
    gpio_set_level(OLED_RST_IO, 1);
    vTaskDelay(50 / portTICK_PERIOD_MS);

    i2c_config_t conf = {
        .mode = I2C_MODE_MASTER,
        .sda_io_num = I2C_MASTER_SDA_IO,
        .scl_io_num = I2C_MASTER_SCL_IO,
        .sda_pullup_en = GPIO_PULLUP_ENABLE,
        .scl_pullup_en = GPIO_PULLUP_ENABLE,
        .master.clk_speed = I2C_MASTER_FREQ_HZ,
    };
    i2c_param_config(I2C_MASTER_NUM, &conf);
    i2c_driver_install(I2C_MASTER_NUM, conf.mode, 0, 0, 0);

    const uint8_t init_cmds[] = {
        0xAE, // Display OFF
        0x20, 0x00, // Set Memory Addressing Mode to Horizontal
        0xB0, // Set Page Start Address
        0xC8, // COM Output Scan Direction
        0x00, // Set low column address
        0x10, // Set high column address
        0x40, // Set start line address
        0x81, 0xFF, // Set contrast control register
        0xA1, // Set Segment Re-map
        0xA6, // Set Normal Display
        0xA8, 0x3F, // Set Multiplex Ratio (64 lines)
        0xA4, // Output RAM to Display
        0xD3, 0x00, // Set Display Offset
        0xD5, 0xF0, // Set Display Clock Divide Ratio/Oscillator Frequency
        0xD9, 0x22, // Set Pre-charge Period
        0xDA, 0x12, // Set COM Pins Hardware Configuration
        0xDB, 0x20, // Set VCOMH Deselect Level
        0x8D, 0x14, // Charge Pump Setting
        0xAF  // Display ON
    };

    for(int i=0; i<sizeof(init_cmds); i++) {
        send_cmd(init_cmds[i]);
    }
    
    ssd1306_clear();
    ssd1306_update();
}

void ssd1306_clear() {
    memset(buffer, 0, sizeof(buffer));
}

void ssd1306_draw_string(int x, int y, const char *str) {
    int cur_x = x;
    while (*str) {
        char c = *str;
        if (c < 32 || c > 127) c = '?';
        int idx = c - 32;
        
        // draw 5 columns of character
        for (int i = 0; i < 5; i++) {
            if (cur_x + i >= OLED_WIDTH) break;
            
            uint8_t col = font5x7[idx][i];
            
            // Draw column pixels
            for (int py = 0; py < 8; py++) {
                if (col & (1 << py)) {
                    int p_x = cur_x + i;
                    int p_y = y + py;
                    if (p_x >= 0 && p_x < OLED_WIDTH && p_y >= 0 && p_y < OLED_HEIGHT) {
                        buffer[p_x + (p_y / 8) * OLED_WIDTH] |= (1 << (p_y % 8));
                    }
                }
            }
        }
        cur_x += 6; // 5 width + 1 spacing
        str++;
    }
}

void ssd1306_update() {
    for (int page = 0; page < 8; page++) {
        send_cmd(0xB0 + page); // Set page address
        send_cmd(0x00);        // Set lower column start address
        send_cmd(0x10);        // Set higher column start address

        i2c_cmd_handle_t handle = i2c_cmd_link_create();
        i2c_master_start(handle);
        i2c_master_write_byte(handle, (OLED_I2C_ADDR << 1) | I2C_MASTER_WRITE, true);
        i2c_master_write_byte(handle, 0x40, true); // Data stream
        i2c_master_write(handle, &buffer[page * OLED_WIDTH], OLED_WIDTH, true);
        i2c_master_stop(handle);
        i2c_master_cmd_begin(I2C_MASTER_NUM, handle, 1000 / portTICK_PERIOD_MS);
        i2c_cmd_link_delete(handle);
    }
}
